function makeSvgImage(bg: string, accent: string, label: string, emoji: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="400" viewBox="0 0 600 400">
    <rect width="600" height="400" fill="${bg}"/>
    <circle cx="480" cy="80" r="110" fill="${accent}" fill-opacity="0.22"/>
    <circle cx="100" cy="340" r="90" fill="${accent}" fill-opacity="0.18"/>
    <text x="300" y="185" text-anchor="middle" font-size="72">${emoji}</text>
    <text x="300" y="255" text-anchor="middle" font-family="system-ui, sans-serif" font-size="22" font-weight="600" fill="#1e293b">${label}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

